#include <iostream>
#include <memory>

#include "Globals.hpp"
#include "platform/IPlatform.hpp"
#include "Scene.hpp"
#include "Sequencer.hpp"

void RegisterAllSprites(Scene& scene);  // Forward declaration of the function generated by the transpiler

bool greenFlagClicked = true;  // To start the project, TODO: Add settings to control this in different ways

#ifndef M_PI
    #define M_PI 3.14159265358979323846
#endif

#if defined(_WIN32) || defined(__linux__)
    #include "platform/desktop/SDLPlatform.hpp"
    #define USE_SDL_PLATFORM
#elif defined(GEKKO)
    #include "platform/gamecube/GameCubePlatform.hpp"
#endif

int main() {
    std::unique_ptr<IPlatform> platform;

#ifdef USE_SDL_PLATFORM
    platform = std::make_unique<SDLPlatform>();
#elif defined(GEKKO)
    platform = std::make_unique<GameCubePlatform>();
#else
    #error "Unsupported platform"
#endif

    if (!platform->Initialize()) {
        std::cerr << "Initialize failed\n";
        return 1;
    }

    Scene scene;
    Sequencer sequencer;
    g_scene = &scene;
    g_sequencer = &sequencer;
    g_platform = platform.get();

    // Create a scene and load all sprites into it
    RegisterAllSprites(scene);

    if (!platform->LoadAllAssets(*g_scene)) {
        std::cerr << "LoadAllAssets failed\n";
        return 1;
    }

    g_sequencer->StartHats(HatType::WHEN_FLAG_CLICKED, *g_scene);  // Start green flag scripts; TODO: Make an option before transpiling on whether this should be automatic

    while (!platform->ShouldClose()) {
        platform->PollEvents();
        double dt = platform->GetDeltaTime();
        g_redrawRequested = false;  // This could be set to true by a block executed while stepping threads
        g_sequencer->StepAllThreads(dt);
        if (g_redrawRequested) {
            platform->BeginFrame();
            platform->RenderScene(*g_scene);
            platform->EndFrame();
        }
        g_timer += dt;  // Update the global timer only when a frame is rendered
    }

    platform->Shutdown();
    return 0;  // Return 0
}